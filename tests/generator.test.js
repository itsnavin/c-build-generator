import test from "node:test";
import assert from "node:assert/strict";
import { generate, validate, defaults, presets } from "../generator.js";
import { zip } from "../zip.js";
import { writeFile, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync } from "node:child_process";

test("all visible option combinations generate coherent files", () => {
  for (const generator of ["make", "cmake"])
    for (const target of Object.keys(presets))
      for (const standard of ["c99", "c11", "c17"])
        for (const mode of ["Debug", "Release"])
          for (const optimization of ["0", "1", "2", "3", "s"])
            for (const warnings of ["basic", "strict"])
              for (const template of ["greeting", "sensor"]) {
                const p = generate({ generator, target, standard, mode, optimization, warnings, template, compiler: presets[target].compiler });
                assert.match(p.files["main.c"], /int main\(void\)/);
                assert.ok(p.files["README.md"].includes(p.binary));
                assert.equal(Object.keys(p.files).length, generator === "cmake" && target !== "native" ? 4 : 3);
                assert.ok(p.files[generator === "make" ? "Makefile" : "CMakeLists.txt"].includes(`-O${optimization}`));
                assert.equal(p.commands.includes(`\n./${p.binary}`), target === "native");
              }
});

test("reject injection, reserved identifiers, invalid enums and unsafe paths", () => {
  for (const name of ["", "1hello", "all", "clean", "install", "test", "ZERO_CHECK", "a b", "../x", "$(shell id)", "x;id", "x\nall:", "x".repeat(41), null]) {
    assert.ok(validate({ name }).errors.name, String(name));
    assert.throws(() => generate({ name }));
  }
  for (const compiler of ["gcc -O2", "gcc;id", "$(id)", "/opt/a b/gcc", "/opt/../gcc", "bin/gcc", "gcc\nid", "gcc#x", null]) {
    assert.ok(validate({ compiler }).errors.compiler, String(compiler));
  }
  for (const sysroot of ["relative", "/a b", "/a;id", "/a$(id)", '/a"b', "/a/../b", "/a//b", "/a\\b", null]) {
    assert.ok(validate({ target: "custom", sysroot }).errors.sysroot, String(sysroot));
  }
  for (const key of ["generator", "target", "standard", "mode", "optimization", "warnings", "template", "processor"]) {
    assert.throws(() => generate({ [key]: "bad" }));
  }
  assert.throws(() => generate({ sysroot: "/opt/sdk" }));
  assert.doesNotThrow(() => generate({ name: "My-app_2", compiler: "/opt/tool-chain/bin/gcc-14", target: "custom", sysroot: "/opt/sdk/sysroot" }));
});

test("GNU Make default compiler, flags, dependency and clean rules", () => {
  const { files } = generate({ target: "aarch64", compiler: presets.aarch64.compiler, sysroot: "/opt/sdk" });
  assert.match(files.Makefile, /\$\(filter default undefined,\$\(origin CC\)\)/);
  assert.match(files.Makefile, /CC := aarch64-linux-gnu-gcc/);
  assert.match(files.Makefile, /\t\$\(CC\) --sysroot=\/opt\/sdk \$\(CPPFLAGS\) \$\(CFLAGS\) -MMD -MP/);
  assert.match(files.Makefile, /\$\(LDFLAGS\).*main.o \$\(LDLIBS\)/);
  assert.match(files.Makefile, /-include build\/make-aarch64.*\/main.d/);
  assert.match(files.Makefile, /clean:\n\trm -rf -- build\/make-aarch64-/);
  assert.doesNotMatch(files.Makefile, /^ +\$\(/m);
});

test("CMake uses target properties and an early external toolchain", () => {
  const p = generate({ generator: "cmake", target: "custom", compiler: "/opt/bin/riscv64-linux-gnu-gcc", processor: "riscv64", sysroot: "/opt/sdk" });
  assert.match(p.files["CMakeLists.txt"], /project\(hello_c LANGUAGES C\)/);
  assert.match(p.files["CMakeLists.txt"], /C_STANDARD_REQUIRED YES/);
  assert.match(p.files["toolchain.cmake"], /CMAKE_SYSTEM_PROCESSOR riscv64/);
  assert.match(p.files["toolchain.cmake"], /CMAKE_SYSROOT "\/opt\/sdk"/);
  assert.match(p.files["toolchain.cmake"], /MODE_PROGRAM NEVER/);
  for (const kind of ["LIBRARY", "INCLUDE", "PACKAGE"]) assert.ok(p.files["toolchain.cmake"].includes(`MODE_${kind} ONLY`));
  assert.match(p.commands, /-DCMAKE_TOOLCHAIN_FILE=toolchain.cmake/);
  assert.doesNotMatch(JSON.stringify(p.files), /C_COMPILER_WORKS/);
});

test("different settings have isolated artifacts; generation is deterministic", () => {
  const base = generate();
  assert.deepEqual(base, generate(defaults));
  for (const variation of [{ target: "aarch64" }, { compiler: "clang" }, { mode: "Release" }, { sysroot: "/opt/sdk", target: "custom" }, { optimization: "2" }]) {
    assert.notEqual(base.directory, generate(variation).directory);
  }
});

test("download ZIP passes Python CRC checks and contains exact generated bytes", async () => {
  const project = generate({ generator: "cmake", target: "aarch64", compiler: presets.aarch64.compiler });
  const dir = await mkdtemp(join(tmpdir(), "c-build-zip-"));
  try {
    await writeFile(join(dir, "starter.zip"), new Uint8Array(await zip(project.files).arrayBuffer()));
    await writeFile(join(dir, "expected.json"), JSON.stringify(project.files));
    execFileSync(process.env.PYTHON || "python3", ["-c", "import zipfile,json,sys; z=zipfile.ZipFile(sys.argv[1]); e=json.load(open(sys.argv[2])); assert z.testzip() is None; assert set(z.namelist())==set(e); assert all(z.read(n).decode()==v for n,v in e.items())", join(dir, "starter.zip"), join(dir, "expected.json")]);
  } finally {
    await rm(dir, { recursive: true });
  }
});
